# Ask the user for input
char = input("Enter a letter: ").lower()

# Check using if-elif-else statements
if char == 'a':
    print("It is a vowel.")
elif char == 'e':
    print("It is a vowel.")
elif char == 'i':
    print("It is a vowel.")
elif char == 'o':
    print("It is a vowel.")
elif char == 'u':
    print("It is a vowel.")
else:
    print("It is a consonant (or not a vowel).")
